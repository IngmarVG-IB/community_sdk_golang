func render(t *template.Template, ref string, data any) ([]byte, error) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, header, ref)
	if err := t.Execute(&buf, data); err != nil {
		return nil, err
	}
	out, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt %s: %w\n%s", t.Name(), err, buf.String())
	}
	return out, nil
}

func allVersions(s *Schema) []*Version {
	var out []*Version
	for _, a := range s.APIs {
		out = append(out, a.Versions...)
	}
	return out
}

func versionsWith(s *Schema, exposure string) []*Version {
	return slices.DeleteFunc(allVersions(s), func(v *Version) bool { return v.Exposure != exposure })
}

// RenderRegistry renders kentikapi/zz_registry.go.
func RenderRegistry(s *Schema) ([]byte, error) {
	return render(registryTmpl, s.Ref, map[string]any{"Versions": allVersions(s)})
}

// RenderAccessors renders kentikapi/zz_accessors.go or kentikapi/experimental/zz_accessors.go.
func RenderAccessors(s *Schema, pkg string) ([]byte, error) {
	exposure := exposureStable
	if pkg == "experimental" {
		exposure = exposureExperimental
	}
	return render(accessorsTmpl, s.Ref, map[string]any{
		"Package": pkg, "Versions": versionsWith(s, exposure), "ConnExpr": "conn",
	})
}

// ManifestEntry is one services[] entry of kentik-api.json.
type ManifestEntry struct {
	Service   string   `json:"service"`
	Version   string   `json:"version"`
	Stability string   `json:"stability"`
	Status    string   `json:"status"`
	Surface   []string `json:"surface"`
}

// legacySurface records hand-written surfaces that predate the generator.
var legacySurface = map[string][]string{
	"cloud_export/v202101beta1": {"kentikapi.Client.Cloud (deprecated hand-written wrapper)", "kentikapi/cloud"},
}

// RenderManifest renders kentik-api.json.
func RenderManifest(s *Schema) ([]byte, error) {
	type source struct {
		Repo string `json:"repo"`
		Ref  string `json:"ref"`
	}
	type legacy struct {
		API    string `json:"api"`
		Status string `json:"status"`
	}
	doc := struct {
		SchemaSource source          `json:"schema_source"`
		Services     []ManifestEntry `json:"services"`
		Legacy       []legacy        `json:"legacy"`
	}{
		SchemaSource: source{Repo: goModule, Ref: s.Ref},
		Legacy:       []legacy{{API: "v5", Status: "deprecated"}},
	}
	for _, v := range allVersions(s) {
		e := ManifestEntry{Service: v.API.Path, Version: v.Name, Stability: v.Stability}
		switch v.Exposure {
		case exposureStable:
			e.Status = "supported"
			e.Surface = append(e.Surface, "kentikapi.Client."+accessorName(v))
			if v.IsAlias {
				e.Surface = append(e.Surface, "kentikapi.Client."+aliasName(v.API))
			}
		case exposureExperimental:
			e.Status = "experimental"
			e.Surface = append(e.Surface, "kentikapi/experimental.Client."+accessorName(v))
		default:
			e.Status = "deprecated"
			e.Surface = append(e.Surface, "kentikapi.Client.Conn (superseded; no accessor)")
		}
		e.Surface = append(e.Surface, legacySurface[v.Dir]...)
		var paged []string
		for _, svc := range v.Services {
			e.Surface = append(e.Surface, svc.FullName)
			for _, m := range svc.Methods {
				if m.Pagination != "" && v.Exposure != exposureNone {
					paged = append(paged, svc.Name+"."+m.Name)
				}
			}
		}
		if len(paged) > 0 {
			e.Surface = append(e.Surface, "paginated (kentikapi.Paginate): "+strings.Join(paged, ", "))
		}
		doc.Services = append(doc.Services, e)
	}
	out, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(out, '\n'), nil
}
