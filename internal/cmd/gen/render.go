const header = "// Code generated by internal/cmd/gen from github.com/kentik/api-schema-public %s. DO NOT EDIT.\n\n"

// accessorExpr is the user-facing accessor for one service, recorded in the registry and manifest.
func accessorExpr(v *Version, svc *Service) string {
	var recv string
	switch v.Exposure {
	case exposureStable:
		recv = "Client."
	case exposureExperimental:
		recv = "experimental.Client."
	default:
		return ""
	}
	expr := recv + accessorName(v) + "()"
	if len(v.Services) > 1 {
		expr += "." + fieldName(v.API.Path, svc.Name)
	}
	return expr
}

var funcs = template.FuncMap{
	"accessor": accessorName,
	"alias":    aliasName,
	"group":    groupTypeName,
	"imp":      importAlias,
	"field":    func(v *Version, s *Service) string { return fieldName(v.API.Path, s.Name) },
	"accexpr":  accessorExpr,
	"stability": func(s string) string {
		return map[string]string{"stable": "Stable", "beta": "Beta", "alpha": "Alpha"}[s]
	},
	"q":     func(s string) string { return fmt.Sprintf("%q", s) },
	"multi": func(v *Version) bool { return len(v.Services) > 1 },
	"first": func(v *Version) *Service { return v.Services[0] },
}

